#!/usr/bin/env python3
"""Write the Samsung tables the native encoder needs as a C header (ssc-uhq OD7, F46).

usage: ssc-extract-tables.py BLOB OUT.h

The header is derived from the user's own blob and must not be committed (D28). Only
the S24U/S26U build (sha256 90c4c1cb...) is known; its two static CELTModes sit at
0x1b9c0 (44.1/48 kHz) and 0x1ba40 (96 kHz), with their pointers filled in by
R_AARCH64_RELATIVE relocations. Everything else comes from exported symbols.
"""
import hashlib
import struct
import sys

KNOWN = {"90c4c1cbd59b0edb9df6d255acc1f752e542e0cb99d3de8e842afc7ca9914ce7": (0x1B9C0, 0x1BA40)}
R_AARCH64_RELATIVE = 0x403


class Elf:
    def __init__(self, data):
        self.d = data
        if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
            sys.exit("not a little-endian ELF64 file")
        (self.phoff, self.shoff) = struct.unpack_from("<QQ", data, 0x20)
        (self.phentsize, self.phnum, self.shentsize, self.shnum) = struct.unpack_from("<HHHH", data, 0x36)
        self.loads = []
        for i in range(self.phnum):
            p_type, _, p_offset, p_vaddr, _, p_filesz, _, _ = struct.unpack_from(
                "<IIQQQQQQ", data, self.phoff + i * self.phentsize)
            if p_type == 1:
                self.loads.append((p_vaddr, p_offset, p_filesz))
        self.sections = []
        for i in range(self.shnum):
            self.sections.append(struct.unpack_from("<IIQQQQIIQQ", data, self.shoff + i * self.shentsize))
        self.rel = {}
        self.syms = {}
        for (_, sh_type, _, _, off, size, link, _, _, entsize) in self.sections:
            if sh_type == 4:  # SHT_RELA
                for k in range(size // 24):
                    r_off, r_info, r_add = struct.unpack_from("<QQq", data, off + 24 * k)
                    if r_info & 0xFFFFFFFF == R_AARCH64_RELATIVE:
                        self.rel[r_off] = r_add
            if sh_type == 11:  # SHT_DYNSYM
                stroff = self.sections[link][4]
                for k in range(size // 24):
                    st_name, _, _, _, st_value, st_size = struct.unpack_from("<IBBHQQ", data, off + 24 * k)
                    end = data.index(b"\0", stroff + st_name)
                    name = data[stroff + st_name:end].decode()
                    if name and st_value:
                        self.syms[name] = (st_value, st_size)

    def off(self, vaddr):
        for (v, o, n) in self.loads:
            if v <= vaddr < v + n:
                return o + vaddr - v
        sys.exit("address 0x%x is not in the file" % vaddr)

    def read(self, vaddr, fmt, n):
        return list(struct.unpack_from("<%d%s" % (n, fmt), self.d, self.off(vaddr)))

    def ptr(self, vaddr):
        if vaddr not in self.rel:
            sys.exit("no relocation at 0x%x" % vaddr)
        return self.rel[vaddr]


def carray(ctype, name, vals, per_line=16):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("   " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(vals), "\n".join(lines))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    if sha not in KNOWN:
        sys.exit("unknown blob %s: the mode addresses are only known for %s" % (sha, ", ".join(KNOWN)))
    elf = Elf(data)
    out = ["/* Generated by tools/ssc-extract-tables.py from the user's blob (sha256 %s).\n"
           "   Samsung data: do not commit (D28). */\n" % sha,
           "#ifndef SSC_TABLES_H\n#define SSC_TABLES_H\n",
           '#define SSC_TABLES_SHA256 "%s"\n' % sha]
    for tag, base, want_fs in (("48", KNOWN[sha][0], 44100), ("96", KNOWN[sha][1], 96000)):
        fs, overlap, nb, eff = elf.read(base, "i", 4)
        nshort, shortsize, nalloc, _ = elf.read(base + 0x18, "i", 4)
        cache_size = elf.read(base + 0x60, "i", 1)[0]
        if (fs, overlap, nb, eff, nshort, shortsize, nalloc) != (want_fs, 108, 22, 21, 8, 108, 11):
            sys.exit("mode at 0x%x does not look like an SSC mode" % base)
        out.append("/* %d Hz mode (blob 0x%x) */\n" % (fs, base))
        out.append("#define SSC_CACHE_SIZE%s %d\n" % (tag, cache_size))
        out.append(carray("opus_int16", "ssc_eBands" + tag, elf.read(elf.ptr(base + 0x10), "h", nb + 1)))
        out.append(carray("unsigned char", "ssc_alloc_shared" + tag, elf.read(elf.ptr(base + 0x28), "B", nalloc * nb), nb))
        out.append(carray("unsigned char", "ssc_alloc_mode" + tag, elf.read(elf.ptr(base + 0x30), "B", nalloc * nb), nb))
        out.append(carray("opus_int16", "ssc_logN" + tag, elf.read(elf.ptr(base + 0x38), "h", nb)))
        out.append(carray("opus_int16", "ssc_cache_index" + tag, elf.read(elf.ptr(base + 0x68), "h", nb * 5), nb))
        out.append(carray("unsigned char", "ssc_cache_bits" + tag, elf.read(elf.ptr(base + 0x70), "B", cache_size)))
    for name, ctype, fmt, n in (("headroom_gain", "opus_int32", "i", 240),
                                ("coeffs96andbelow", "opus_int32", "i", 5),
                                ("coeffs", "opus_int32", "i", 5)):
        if name not in elf.syms:
            sys.exit("blob has no symbol %s" % name)
        out.append(carray(ctype, "ssc_" + name, elf.read(elf.syms[name][0], fmt, n), 8))
    out.append("#endif\n")
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
